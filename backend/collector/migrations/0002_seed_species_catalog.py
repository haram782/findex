def category_for(species):
    for category, names in CATEGORY_GROUPS.items():
        if species in names:
            return category
    return "fish"


def seed_catalog(apps, schema_editor):
    species_catalog = apps.get_model("collector", "SpeciesCatalog")
    species_catalog.objects.bulk_create(
        [
            species_catalog(
                species=species,
                category=category_for(species),
                is_official=True,
            )
            for species in OFFICIAL_SPECIES
        ],
        ignore_conflicts=True,
    )


def remove_catalog(apps, schema_editor):
    species_catalog = apps.get_model("collector", "SpeciesCatalog")
    species_catalog.objects.filter(species__in=OFFICIAL_SPECIES).delete()


